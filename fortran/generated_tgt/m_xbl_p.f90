              IF (wake) THEN
                IF (htarg .LT. 1.01) THEN
                  htarg = 1.01
                ELSE
                  htarg = htarg
                END IF
              ELSE IF (htarg .LT. hmax) THEN
                htarg = hmax
              ELSE
                htarg = htarg
              END IF
