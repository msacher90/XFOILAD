            vs2(4, 3) = hk2_d2*hkref
            vs2(4, 4) = (hk2_u2*hkref+sens/ueref)*u2_uei
            vsrez(4) = -(hkref**2*(hk2/hkref-1.0)) - sens*(u2/ueref-1.0)
