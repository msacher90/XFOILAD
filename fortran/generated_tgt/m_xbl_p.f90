              y2 = vsrez(1)/(10.0*cti)
            ELSE
              y2 = -(vsrez(1)/(10.0*cti))
            END IF
            IF (dmax .LT. y2) THEN
              dmax = y2
            ELSE
              dmax = dmax
            END IF
          END IF
