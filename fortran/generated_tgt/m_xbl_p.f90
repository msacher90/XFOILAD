!CC        IF(DMAX .LE. 0.1) GO TO 110
        IF (dmax .GT. 0.1) THEN
!
!------- the current solution is garbage --> extrapolate values instead
          IF (ibl .GT. 3) THEN
            IF (ibl .LE. iblte(is)) THEN
              thi = thet(ibm, is)*(xssi(ibl, is)/xssi(ibm, is))**0.5
