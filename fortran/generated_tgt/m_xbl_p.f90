              IF (tran) THEN
                itran(is) = ibl
                IF (cti .LE. 0.0) THEN
                  cti = 0.03
                  s2 = cti
                END IF
              ELSE
                itran(is) = ibl + 2
              END IF
            END IF
          END IF
