      amcrit = acrit(is)
!
!---- set forced transition arc length position
      CALL XIFSET(is)
!
!---- initialize similarity station with Thwaites' formula
      ibl = 2
      xsi = xssi(ibl, is)
      uei = uedg(ibl, is)
!      BULE = LOG(UEDG(IBL+1,IS)/UEI) / LOG(XSSI(IBL+1,IS)/XSI)
!      BULE = MAX( -.08 , BULE )
      bule = 1.0
      pwr1 = xsi**bule
      ucon = uei/pwr1
      pwy1 = 1.0 - bule
      pwr1 = xsi**pwy1
      tsq = 0.45/(ucon*(5.0*bule+1.0)*reybl)*pwr1
      thi = SQRT(tsq)
      dsi = 2.2*thi
      ami = 0.0
!
!---- initialize Ctau for first turbulent station
      cti = 0.03
!
      tran = .false.
      turb = .false.
      itran(is) = iblte(is)
!
!---- march downstream
      DO ibl=2,nbl(is)
        ibm = ibl - 1
!
        iw = ibl - iblte(is)
!
        simi = ibl .EQ. 2
        wake = ibl .GT. iblte(is)
