              IF (vsrez(1)/10.0 .GE. 0.) THEN
                y2 = vsrez(1)/10.0
              ELSE
                y2 = -(vsrez(1)/10.0)
              END IF
              IF (dmax .LT. y2) THEN
                dmax = y2
              ELSE
                dmax = dmax
              END IF
            END IF
