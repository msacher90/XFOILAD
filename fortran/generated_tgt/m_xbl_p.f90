            GOTO 100
          ELSE
            ami = ampl2
            IF (tran) itran(is) = ibl
            IF (.NOT.tran) itran(is) = ibl + 2
          END IF
        END IF
!
!------- set all other extrapolated values for current station
        IF (ibl .LT. itran(is)) CALL BLVAR(1)
        IF (ibl .GE. itran(is)) CALL BLVAR(2)
        IF (wake) CALL BLVAR(3)
!
        IF (ibl .LT. itran(is)) CALL BLMID(1)
        IF (ibl .GE. itran(is)) CALL BLMID(2)
        IF (wake) CALL BLMID(3)
!
!------ pick up here after the Newton iterations
!
 20     sens = sennew
!
!------ store primary variables
        IF (ibl .LT. itran(is)) ctau(ibl, is) = ami
        IF (ibl .GE. itran(is)) ctau(ibl, is) = cti
        thet(ibl, is) = thi
        dstr(ibl, is) = dsi
        uedg(ibl, is) = uei
        mass(ibl, is) = dsi*uei
        tau(ibl, is) = 0.5*r2*u2*u2*cf2
        dis(ibl, is) = r2*u2*u2*u2*di2*hs2*0.5
        ctq(ibl, is) = cq2
        delt(ibl, is) = de2
        tstr(ibl, is) = hs2*t2
!
!------ set "1" variables to "2" variables for next streamwise station
        CALL BLPRV(xsi, ami, cti, thi, dsi, dswaki, uei)
        CALL BLKIN()
        CALL BLC_1FROM2()
!
!
!------ turbulent intervals will follow transition interval or TE
        IF (tran .OR. ibl .EQ. iblte(is)) THEN
          turb = .true.
!
!------- save transition location
          tforce(is) = trforc
          xssitr(is) = xt
        END IF
!
        tran = .false.
      END DO
!
!
!---- XFOILAD: cycle of the transition interval (see i_xfoil)
      IF (itran(is) .NE. itrold) THEN
        xad_trstab = -1
        IF (itran(is) - itrold .GE. 0.) THEN
          abs0 = itran(is) - itrold
        ELSE
          abs0 = -(itran(is)-itrold)
        END IF
        IF (itran(is) .EQ. xad_trprv(is) .AND. abs0 .EQ. 1) THEN
          xad_trnfl(is) = xad_trnfl(is) + 1
          IF (xad_trnfl(is) .GE. xad_trnflmax) THEN
            IF (xad_rlxcap*xad_rlxfac .LT. xad_rlxmin) THEN
              xad_rlxcap = xad_rlxmin
            ELSE
              xad_rlxcap = xad_rlxcap*xad_rlxfac
            END IF
            IF (show_output) WRITE(*, *) &
&                            'MRCHDU: transition cycle on side', is, &
&                            ', Newton step limited to', xad_rlxcap
          END IF
        END IF
        xad_trprv(is) = itrold
      END IF
      xad_mfprv(is) = xad_mfcur(is)
    END DO
!
!
!---- XFOILAD: transition intervals unchanged for xad_trnstab iterations:
!     the step limit is released progressively (factor 2 per stable period)
    xad_trstab = xad_trstab + 1
    IF (xad_trstab .GE. xad_trnstab .AND. xad_rlxcap .LT. 1.0) THEN
      IF (2.0*xad_rlxcap .GT. 1.0) THEN
        xad_rlxcap = 1.0
      ELSE
        xad_rlxcap = 2.0*xad_rlxcap
      END IF
      xad_trstab = 0
    END IF
    GOTO 120
 100 RETURN
 110 RETURN
 120 CONTINUE
99001 FORMAT(' MRCHDU: Convergence failed at', i4, '  side', i2, &
&          '    Res =', e12.4)
  END FUNCTION MRCHDU

