              x4 = vsrez(2)/thi
            ELSE
              x4 = -(vsrez(2)/thi)
            END IF
            IF (vsrez(3)/dsi .GE. 0.) THEN
              y4 = vsrez(3)/dsi
            ELSE
              y4 = -(vsrez(3)/dsi)
            END IF
            IF (vsrez(4)/uei .GE. 0.) THEN
              z1 = vsrez(4)/uei
            ELSE
              z1 = -(vsrez(4)/uei)
            END IF
