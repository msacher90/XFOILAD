            CALL GAUSS(4, 4, vs2, vsrez, 1)
            IF (vsrez(2)/thi .GE. 0.) THEN
              x3 = vsrez(2)/thi
            ELSE
              x3 = -(vsrez(2)/thi)
            END IF
