!
          IF (ibl .EQ. iblte(is) + 1) THEN
            tte = thet(iblte(1), 1) + thet(iblte(2), 2)
            dte = dstr(iblte(1), 1) + dstr(iblte(2), 2) + ante
            cte = (ctau(iblte(1), 1)*thet(iblte(1), 1)+ctau(iblte(2), 2)&
&             *thet(iblte(2), 2))/tte
