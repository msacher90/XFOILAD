          dsw = dsi - dswaki
          CALL DSLIM(dsw, thi, uei, msq, hklim)
          dsi = dsw + dswaki
!
          IF (dmax .LE. deps) GOTO 20
        END DO
!
!
        IF (show_output) WRITE(*, 99001) ibl, is, dmax
