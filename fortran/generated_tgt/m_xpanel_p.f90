!CC         SIG2 = (SIG(JQ) - SIG(JO))*DSIP
!CC         SIG0 = (SIG(JP) - SIG(JO))*DSIO
!CC         SSUM = SIG2 + SIG0
!CC         SDIF = SIG2 - SIG0
!
