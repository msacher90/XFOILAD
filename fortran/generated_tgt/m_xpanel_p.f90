            j = ipan(jbl, js)
            ue_m = -(vti(ibl, is)*vti(jbl, js)*dij(i, j))
            dui = dui + ue_m*mass(jbl, js)
          END DO
        END DO
!
        uedg(ibl, is) = uinv(ibl, is) + dui
      END DO
    END DO
  END SUBROUTINE UESET

