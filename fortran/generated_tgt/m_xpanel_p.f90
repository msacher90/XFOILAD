&       sigte + hopi*(pgamx1*x1p+pgamx2*x2p+pgamyy*yyp)*gamte
!
!----- dPsi/dP
      z_qdof0 = z_qdof0 + hopi*psig*0.5*(qf0(jp)-qf0(jo))*scs - hopi*&
&       pgam*0.5*(qf0(jp)-qf0(jo))*sds
      z_qdof1 = z_qdof1 + hopi*psig*0.5*(qf1(jp)-qf1(jo))*scs - hopi*&
&       pgam*0.5*(qf1(jp)-qf1(jo))*sds
      z_qdof2 = z_qdof2 + hopi*psig*0.5*(qf2(jp)-qf2(jo))*scs - hopi*&
&       pgam*0.5*(qf2(jp)-qf2(jo))*sds
      z_qdof3 = z_qdof3 + hopi*psig*0.5*(qf3(jp)-qf3(jo))*scs - hopi*&
&       pgam*0.5*(qf3(jp)-qf3(jo))*sds
!
    END IF
!
!
!**** Freestream terms
 100 psi = psi + qinf*(cosa*yi-sina*xi)
!
!---- dPsi/dn
    psi_ni = psi_ni + qinf*(cosa*nyi-sina*nxi)
!
    qtan1 = qtan1 + qinf*nyi
    qtan2 = qtan2 - qinf*nxi
!
!---- dPsi/dQinf
    z_qinf = z_qinf + (cosa*yi-sina*xi)
!
!---- dPsi/dalfa
    z_alfa = z_alfa - qinf*(sina*yi+cosa*xi)
!
    IF (.NOT.limage) THEN
      RETURN
    ELSE
!
!
!
      DO jo=1,n
        jp = jo + 1
!
        jm = jo - 1
        jq = jp + 1
!
        IF (jo .EQ. 1) THEN
          jm = jo
        ELSE IF (jo .EQ. n - 1) THEN
          jq = jp
        ELSE IF (jo .EQ. n) THEN
          jp = 1
          IF ((x(jo)-x(jp))**2 + (y(jo)-y(jp))**2 .LT. seps**2) GOTO &
&            99999
        END IF
!
        arg1 = (x(jo)-x(jp))**2 + (y(jo)-y(jp))**2
        dso = SQRT(arg1)
!
!------ skip null panel
! if (dso/=0.0) then
        result1 = EPSILON(0.)
        result2 = EPSILON(0.)
        IF (.NOT.(dso .GE. 0. - result1 .AND. dso .LE. 0. + result2)) &
&       THEN
!
          dsio = 1.0/dso
!
!cc     APAN = APANEL(JO)
          apan = pi - apanel(jo) + 2.0*alfa
!
          xjo = x(jo) + 2.0*(yimage+y(jo))*sina
          yjo = y(jo) - 2.0*(yimage+y(jo))*cosa
          xjp = x(jp) + 2.0*(yimage+y(jp))*sina
          yjp = y(jp) - 2.0*(yimage+y(jp))*cosa
!
          rx1 = xi - xjo
          ry1 = yi - yjo
          rx2 = xi - xjp
          ry2 = yi - yjp
!
          sx = (xjp-xjo)*dsio
          sy = (yjp-yjo)*dsio
!
          x1 = sx*rx1 + sy*ry1
          x2 = sx*rx2 + sy*ry2
          yy = sx*ry1 - sy*rx1
!
          rs1 = rx1*rx1 + ry1*ry1
          rs2 = rx2*rx2 + ry2*ry2
!
!------ set reflection flag SGN to avoid branch problems with arctan
          IF (io .GE. 1 .AND. io .LE. n) THEN
!------- no problem on airfoil surface
            sgn = 1.0
          ELSE
!------- make sure arctan falls between  -/+  Pi/2
            sgn = SIGN(1.0, yy)
          END IF
!
!------ set log(r^2) and arctan(x/y), correcting for reflection if any
          g1 = LOG(rs1)
          t1 = ATAN2(sgn*x1, sgn*yy) + (0.5-0.5*sgn)*pi
!
          g2 = LOG(rs2)
          t2 = ATAN2(sgn*x2, sgn*yy) + (0.5-0.5*sgn)*pi
!
          x1i = sx*nxi + sy*nyi
          x2i = sx*nxi + sy*nyi
          yyi = sx*nyi - sy*nxi
!
          IF (geolin) THEN
            nxo = nx(jo)
            nyo = ny(jo)
            nxp = nx(jp)
            nyp = ny(jp)
!
            x1o = -(((rx1-x1*sx)*nxo+(ry1-x1*sy)*nyo)*dsio) - (sx*nxo+sy&
&             *nyo)
            x1p = ((rx1-x1*sx)*nxp+(ry1-x1*sy)*nyp)*dsio
            x2o = -(((rx2-x2*sx)*nxo+(ry2-x2*sy)*nyo)*dsio)
            x2p = ((rx2-x2*sx)*nxp+(ry2-x2*sy)*nyp)*dsio - (sx*nxp+sy*&
&             nyp)
            yyo = ((rx1+x1*sy)*nyo-(ry1-x1*sx)*nxo)*dsio - (sx*nyo-sy*&
&             nxo)
            yyp = -(((rx1-x1*sy)*nyp-(ry1+x1*sx)*nxp)*dsio)
          END IF
!
          IF (jo .EQ. n) THEN
            GOTO 120
          ELSE
!
            IF (siglin) THEN
!
!------- set up midpoint quantities
              x0 = 0.5*(x1+x2)
              rs0 = x0*x0 + yy*yy
              g0 = LOG(rs0)
              t0 = ATAN2(sgn*x0, sgn*yy) + (0.5-0.5*sgn)*pi
!
!------- calculate source contribution to Psi  for  1-0  half-panel
              dxinv = 1.0/(x1-x0)
              psum = x0*(t0-apan) - x1*(t1-apan) + 0.5*yy*(g1-g0)
              pdif = ((x1+x0)*psum+rs1*(t1-apan)-rs0*(t0-apan)+(x0-x1)*&
&               yy)*dxinv
!
              psx1 = -(t1-apan)
              psx0 = t0 - apan
              psyy = 0.5*(g1-g0)
!
              pdx1 = ((x1+x0)*psx1+psum+2.0*x1*(t1-apan)-pdif)*dxinv
              pdx0 = ((x1+x0)*psx0+psum-2.0*x0*(t0-apan)+pdif)*dxinv
              pdyy = ((x1+x0)*psyy+2.0*(x0-x1+yy*(t1-t0)))*dxinv
!
              arg1 = (x(jp)-x(jm))**2 + (y(jp)-y(jm))**2
              dsm = SQRT(arg1)
              dsim = 1.0/dsm
!
!CC      SIG0 = (SIG(JP) - SIG(JO))*DSIO
!CC      SIG1 = (SIG(JP) - SIG(JM))*DSIM
!CC      SSUM = SIG0 + SIG1
!CC      SDIF = SIG0 - SIG1
!
              ssum = (sig(jp)-sig(jo))*dsio + (sig(jp)-sig(jm))*dsim
              sdif = (sig(jp)-sig(jo))*dsio - (sig(jp)-sig(jm))*dsim
!
              psi = psi + qopi*(psum*ssum+pdif*sdif)
!
!------- dPsi/dm
              dzdm(jm) = dzdm(jm) + qopi*(-(psum*dsim)+pdif*dsim)
              dzdm(jo) = dzdm(jo) + qopi*(-(psum*dsio)-pdif*dsio)
              dzdm(jp) = dzdm(jp) + qopi*(psum*(dsio+dsim)+pdif*(dsio-&
&               dsim))
!
!------- dPsi/dni
              psni = psx1*x1i + psx0*(x1i+x2i)*0.5 + psyy*yyi
              pdni = pdx1*x1i + pdx0*(x1i+x2i)*0.5 + pdyy*yyi
              psi_ni = psi_ni + qopi*(psni*ssum+pdni*sdif)
!
              qtanm = qtanm + qopi*(psni*ssum+pdni*sdif)
!
              dqdm(jm) = dqdm(jm) + qopi*(-(psni*dsim)+pdni*dsim)
              dqdm(jo) = dqdm(jo) + qopi*(-(psni*dsio)-pdni*dsio)
              dqdm(jp) = dqdm(jp) + qopi*(psni*(dsio+dsim)+pdni*(dsio-&
&               dsim))
!
!
!------- calculate source contribution to Psi  for  0-2  half-panel
              dxinv = 1.0/(x0-x2)
              psum = x2*(t2-apan) - x0*(t0-apan) + 0.5*yy*(g0-g2)
              pdif = ((x0+x2)*psum+rs0*(t0-apan)-rs2*(t2-apan)+(x2-x0)*&
&               yy)*dxinv
!
              psx0 = -(t0-apan)
              psx2 = t2 - apan
              psyy = 0.5*(g0-g2)
!
              pdx0 = ((x0+x2)*psx0+psum+2.0*x0*(t0-apan)-pdif)*dxinv
              pdx2 = ((x0+x2)*psx2+psum-2.0*x2*(t2-apan)+pdif)*dxinv
              pdyy = ((x0+x2)*psyy+2.0*(x2-x0+yy*(t0-t2)))*dxinv
!
              arg1 = (x(jq)-x(jo))**2 + (y(jq)-y(jo))**2
              dsp = SQRT(arg1)
              dsip = 1.0/dsp
!
!CC         SIG2 = (SIG(JQ) - SIG(JO))*DSIP
!CC         SIG0 = (SIG(JP) - SIG(JO))*DSIO
!CC         SSUM = SIG2 + SIG0
!CC         SDIF = SIG2 - SIG0
!
              ssum = (sig(jq)-sig(jo))*dsip + (sig(jp)-sig(jo))*dsio
              sdif = (sig(jq)-sig(jo))*dsip - (sig(jp)-sig(jo))*dsio
!
              psi = psi + qopi*(psum*ssum+pdif*sdif)
!
!------- dPsi/dm
              dzdm(jo) = dzdm(jo) + qopi*(-(psum*(dsip+dsio))-pdif*(dsip&
&               -dsio))
              dzdm(jp) = dzdm(jp) + qopi*(psum*dsio-pdif*dsio)
              dzdm(jq) = dzdm(jq) + qopi*(psum*dsip+pdif*dsip)
!
!------- dPsi/dni
              psni = psx0*(x1i+x2i)*0.5 + psx2*x2i + psyy*yyi
              pdni = pdx0*(x1i+x2i)*0.5 + pdx2*x2i + pdyy*yyi
              psi_ni = psi_ni + qopi*(psni*ssum+pdni*sdif)
!
              qtanm = qtanm + qopi*(psni*ssum+pdni*sdif)
!
              dqdm(jo) = dqdm(jo) + qopi*(-(psni*(dsip+dsio))-pdni*(dsip&
&               -dsio))
              dqdm(jp) = dqdm(jp) + qopi*(psni*dsio-pdni*dsio)
              dqdm(jq) = dqdm(jq) + qopi*(psni*dsip+pdni*dsip)
!
            END IF
!
!------ calculate vortex panel contribution to Psi
            dxinv = 1.0/(x1-x2)
            psis = 0.5*x1*g1 - 0.5*x2*g2 + x2 - x1 + yy*(t1-t2)
            psid = ((x1+x2)*psis+0.5*(rs2*g2-rs1*g1+x1*x1-x2*x2))*dxinv
!
            psx1 = 0.5*g1
            psx2 = -(.5*g2)
            psyy = t1 - t2
!
            pdx1 = ((x1+x2)*psx1+psis-x1*g1-psid)*dxinv
            pdx2 = ((x1+x2)*psx2+psis+x2*g2+psid)*dxinv
            pdyy = ((x1+x2)*psyy-yy*(g1-g2))*dxinv
!
            gsum1 = gamu(jp, 1) + gamu(jo, 1)
            gsum2 = gamu(jp, 2) + gamu(jo, 2)
            gdif1 = gamu(jp, 1) - gamu(jo, 1)
            gdif2 = gamu(jp, 2) - gamu(jo, 2)
!
            gsum = gam(jp) + gam(jo)
            gdif = gam(jp) - gam(jo)
!
            psi = psi - qopi*(psis*gsum+psid*gdif)
!
!------ dPsi/dGam
            dzdg(jo) = dzdg(jo) - qopi*(psis-psid)
            dzdg(jp) = dzdg(jp) - qopi*(psis+psid)
!
!------ dPsi/dni
            psni = psx1*x1i + psx2*x2i + psyy*yyi
            pdni = pdx1*x1i + pdx2*x2i + pdyy*yyi
            psi_ni = psi_ni - qopi*(gsum*psni+gdif*pdni)
!
            qtan1 = qtan1 - qopi*(gsum1*psni+gdif1*pdni)
            qtan2 = qtan2 - qopi*(gsum2*psni+gdif2*pdni)
!
            dqdg(jo) = dqdg(jo) - qopi*(psni-pdni)
            dqdg(jp) = dqdg(jp) - qopi*(psni+pdni)
!
            IF (geolin) THEN
!
!------- dPsi/dn
              dzdn(jo) = dzdn(jo) - qopi*gsum*(psx1*x1o+psx2*x2o+psyy*&
&               yyo) - qopi*gdif*(pdx1*x1o+pdx2*x2o+pdyy*yyo)
              dzdn(jp) = dzdn(jp) - qopi*gsum*(psx1*x1p+psx2*x2p+psyy*&
&               yyp) - qopi*gdif*(pdx1*x1p+pdx2*x2p+pdyy*yyp)
!------- dPsi/dP
              z_qdof0 = z_qdof0 - qopi*((psis-psid)*qf0(jo)+(psis+psid)*&
&               qf0(jp))
              z_qdof1 = z_qdof1 - qopi*((psis-psid)*qf1(jo)+(psis+psid)*&
&               qf1(jp))
              z_qdof2 = z_qdof2 - qopi*((psis-psid)*qf2(jo)+(psis+psid)*&
&               qf2(jp))
              z_qdof3 = z_qdof3 - qopi*((psis-psid)*qf3(jo)+(psis+psid)*&
&               qf3(jp))
            END IF
          END IF
        END IF
      END DO
!
!
!
 120  psig = 0.5*yy*(g1-g2) + x2*(t2-apan) - x1*(t1-apan)
      pgam = 0.5*x1*g1 - 0.5*x2*g2 + x2 - x1 + yy*(t1-t2)
!
      psigx1 = -(t1-apan)
      psigx2 = t2 - apan
      psigyy = 0.5*(g1-g2)
      pgamx1 = 0.5*g1
      pgamx2 = -(.5*g2)
      pgamyy = t1 - t2
!
      psigni = psigx1*x1i + psigx2*x2i + psigyy*yyi
      pgamni = pgamx1*x1i + pgamx2*x2i + pgamyy*yyi
!
!---- TE panel source and vortex strengths
      sigte1 = 0.5*scs*(gamu(jp, 1)-gamu(jo, 1))
      sigte2 = 0.5*scs*(gamu(jp, 2)-gamu(jo, 2))
      gamte1 = -(.5*sds*(gamu(jp, 1)-gamu(jo, 1)))
      gamte2 = -(.5*sds*(gamu(jp, 2)-gamu(jo, 2)))
!
      sigte = 0.5*scs*(gam(jp)-gam(jo))
      gamte = -(.5*sds*(gam(jp)-gam(jo)))
!
!---- TE panel contribution to Psi
      psi = psi + hopi*(psig*sigte-pgam*gamte)
!
!---- dPsi/dGam
      dzdg(jo) = dzdg(jo) - hopi*psig*scs*0.5
      dzdg(jp) = dzdg(jp) + hopi*psig*scs*0.5
!
      dzdg(jo) = dzdg(jo) - hopi*pgam*sds*0.5
      dzdg(jp) = dzdg(jp) + hopi*pgam*sds*0.5
!
!---- dPsi/dni
      psi_ni = psi_ni + hopi*(psigni*sigte-pgamni*gamte)
!
      qtan1 = qtan1 + hopi*(psigni*sigte1-pgamni*gamte1)
      qtan2 = qtan2 + hopi*(psigni*sigte2-pgamni*gamte2)
!
      dqdg(jo) = dqdg(jo) - hopi*(psigni*0.5*scs+pgamni*0.5*sds)
      dqdg(jp) = dqdg(jp) + hopi*(psigni*0.5*scs+pgamni*0.5*sds)
!
      IF (geolin) THEN
!
!----- dPsi/dn
        dzdn(jo) = dzdn(jo) + hopi*(psigx1*x1o+psigx2*x2o+psigyy*yyo)*&
&         sigte - hopi*(pgamx1*x1o+pgamx2*x2o+pgamyy*yyo)*gamte
        dzdn(jp) = dzdn(jp) + hopi*(psigx1*x1p+psigx2*x2p+psigyy*yyp)*&
&         sigte - hopi*(pgamx1*x1p+pgamx2*x2p+pgamyy*yyp)*gamte
!
!----- dPsi/dP
        z_qdof0 = z_qdof0 + hopi*psig*0.5*(qf0(jp)-qf0(jo))*scs + hopi*&
&         pgam*0.5*(qf0(jp)-qf0(jo))*sds
        z_qdof1 = z_qdof1 + hopi*psig*0.5*(qf1(jp)-qf1(jo))*scs + hopi*&
&         pgam*0.5*(qf1(jp)-qf1(jo))*sds
        z_qdof2 = z_qdof2 + hopi*psig*0.5*(qf2(jp)-qf2(jo))*scs + hopi*&
&         pgam*0.5*(qf2(jp)-qf2(jo))*sds
        z_qdof3 = z_qdof3 + hopi*psig*0.5*(qf3(jp)-qf3(jo))*scs + hopi*&
&         pgam*0.5*(qf3(jp)-qf3(jo))*sds
!
      END IF
    END IF
99999 CONTINUE
  END SUBROUTINE PSILIN

!*** XFOILAD: copy of PSILIN without the QTAN1/QTAN2 (GAMU) part, used by
!    XYWAKE. With the shared PSILIN, Tapenade judged GAMU inactive inside
!    XYWAKE and reset its derivative, losing the d(QINVU wake)/d(geometry)
!    contribution computed later by QWCALC.
  SUBROUTINE PSILIN_XW(i, xi, yi, nxi, nyi, psi, psi_ni, geolin, siglin)
    USE I_XFOIL
    IMPLICIT NONE
!
!
!
!*** Start of declarations rewritten by SPAG
!
! Dummy arguments
!
    LOGICAL :: geolin, siglin
    INTEGER :: i
    REAL :: nxi, nyi, psi, psi_ni, xi, yi
! intent (in) Geolin, I, Nxi, Nyi, Siglin, Xi, Yi
! intent (inout) Psi, Psi_ni
!
! Local variables
!
    REAL :: apan, dsim, dsio, dsip, dsm, dso, dsp, dxinv, g0, g1, g2, &
&   gamte1, gamte2, gdif, gdif1, gdif2, gsum, gsum1, gsum2, nxo, nxp, &
&   nyo, nyp, pdif, pdni, pdx0, pdx1, pdx2, pdyy, pgam, pgamni, pgamx1, &
&   pgamx2, pgamyy, psid, psig, psigni, psigx1, psigx2, psigyy, psis, &
&   psni, psum, psx0, psx1, psx2, psyy, qtanm, rs0, rs1, rs2, rx1, rx2, &
&   ry1, ry2, scs, sdif, sds, seps, sgn, sigte1, sigte2, ssum, sx, sy, &
&   t0, t1, t2, x0, x1, x1i, x1o, x1p, x2, x2i, x2o, x2p, xjo
    REAL :: xjp, yjo
    INTEGER :: io, jm, jo, jp, jq
    REAL :: yjp, yy, yyi, yyo, yyp
    INTRINSIC COS
    INTRINSIC SIN
    INTRINSIC SQRT
    INTRINSIC EPSILON
    INTRINSIC SIGN
    INTRINSIC LOG
    INTRINSIC ATAN2
    REAL :: arg1
    REAL :: result1
    REAL :: result2
!
!*** End of declarations rewritten by SPAG
!
!
!*** Start of declarations rewritten by SPAG
!
! Dummy arguments
!
!
! Local variables
!
!
!*** End of declarations rewritten by SPAG
!
!-----------------------------------------------------------------------
!     Calculates current streamfunction Psi at panel node or wake node
!     I due to freestream and all bound vorticity Gam on the airfoil.
!     Sensitivities of Psi with respect to alpha (Z_ALFA) and inverse
!     Qspec DOFs (Z_QDOF0,Z_QDOF1) which influence Gam in inverse cases.
!     Also calculates the sensitivity vector dPsi/dGam (DZDG).
!
!     If SIGLIN=True, then Psi includes the effects of the viscous
!     source distribution Sig and the sensitivity vector dPsi/dSig
!     (DZDM) is calculated.
!
!     If GEOLIN=True, then the geometric sensitivity vector dPsi/dn
!     is calculated, where n is the normal motion of the jth node.
!
!          Airfoil:  1   < I < N
!          Wake:     N+1 < I < N+NW
!-----------------------------------------------------------------------
!
!---- distance tolerance for determining if two points are the same
    seps = (s(n)-s(1))*1.0e-5
!
    io = i
!
    cosa = COS(alfa)
    sina = SIN(alfa)
!
    DO jo=1,n
      dzdg(jo) = 0.0
      dzdn(jo) = 0.0
      dqdg(jo) = 0.0
    END DO
!
    DO jo=1,n
      dzdm(jo) = 0.0
      dqdm(jo) = 0.0
    END DO
!
    z_qinf = 0.
    z_alfa = 0.
    z_qdof0 = 0.
    z_qdof1 = 0.
    z_qdof2 = 0.
    z_qdof3 = 0.
!
    psi = 0.
    psi_ni = 0.
!
    qtanm = 0.
!
    IF (sharp) THEN
      scs = 1.0
      sds = 0.0
    ELSE
      scs = ante/dste
      sds = aste/dste
    END IF
!
    DO jo=1,n
      jp = jo + 1
!
      jm = jo - 1
      jq = jp + 1
!
      IF (jo .EQ. 1) THEN
        jm = jo
      ELSE IF (jo .EQ. n - 1) THEN
        jq = jp
      ELSE IF (jo .EQ. n) THEN
        jp = 1
        IF ((x(jo)-x(jp))**2 + (y(jo)-y(jp))**2 .LT. seps**2) GOTO 100
      END IF
!
      arg1 = (x(jo)-x(jp))**2 + (y(jo)-y(jp))**2
      dso = SQRT(arg1)
!
!------ skip null panel
! if (dso/=0.0) then 
      result1 = EPSILON(0.)
      result2 = EPSILON(0.)
      IF (.NOT.(dso .GE. 0. - result1 .AND. dso .LE. 0. + result2)) THEN
!
        dsio = 1.0/dso
!
        apan = apanel(jo)
!
        rx1 = xi - x(jo)
        ry1 = yi - y(jo)
        rx2 = xi - x(jp)
        ry2 = yi - y(jp)
!
        sx = (x(jp)-x(jo))*dsio
        sy = (y(jp)-y(jo))*dsio
!
        x1 = sx*rx1 + sy*ry1
        x2 = sx*rx2 + sy*ry2
        yy = sx*ry1 - sy*rx1
!
        rs1 = rx1*rx1 + ry1*ry1
        rs2 = rx2*rx2 + ry2*ry2
!
!------ set reflection flag SGN to avoid branch problems with arctan
        IF (io .GE. 1 .AND. io .LE. n) THEN
!------- no problem on airfoil surface
          sgn = 1.0
        ELSE
!------- make sure arctan falls between  -/+  Pi/2
          sgn = SIGN(1.0, yy)
        END IF
!
!------ set log(r^2) and arctan(x/y), correcting for reflection if any
        IF (io .NE. jo .AND. rs1 .GT. 0.0) THEN
          g1 = LOG(rs1)
          t1 = ATAN2(sgn*x1, sgn*yy) + (0.5-0.5*sgn)*pi
        ELSE
          g1 = 0.0
          t1 = 0.0
        END IF
!
        IF (io .NE. jp .AND. rs2 .GT. 0.0) THEN
          g2 = LOG(rs2)
          t2 = ATAN2(sgn*x2, sgn*yy) + (0.5-0.5*sgn)*pi
        ELSE
          g2 = 0.0
          t2 = 0.0
        END IF
!
        x1i = sx*nxi + sy*nyi
        x2i = sx*nxi + sy*nyi
        yyi = sx*nyi - sy*nxi
!
        IF (geolin) THEN
          nxo = nx(jo)
          nyo = ny(jo)
          nxp = nx(jp)
          nyp = ny(jp)
!
          x1o = -(((rx1-x1*sx)*nxo+(ry1-x1*sy)*nyo)*dsio) - (sx*nxo+sy*&
&           nyo)
          x1p = ((rx1-x1*sx)*nxp+(ry1-x1*sy)*nyp)*dsio
          x2o = -(((rx2-x2*sx)*nxo+(ry2-x2*sy)*nyo)*dsio)
          x2p = ((rx2-x2*sx)*nxp+(ry2-x2*sy)*nyp)*dsio - (sx*nxp+sy*nyp)
          yyo = ((rx1+x1*sy)*nyo-(ry1-x1*sx)*nxo)*dsio - (sx*nyo-sy*nxo)
          yyp = -(((rx1-x1*sy)*nyp-(ry1+x1*sx)*nxp)*dsio)
        END IF
!
        IF (jo .EQ. n) THEN
          GOTO 110
        ELSE
!
          IF (siglin) THEN
!
!------- set up midpoint quantities
            x0 = 0.5*(x1+x2)
            rs0 = x0*x0 + yy*yy
            g0 = LOG(rs0)
            t0 = ATAN2(sgn*x0, sgn*yy) + (0.5-0.5*sgn)*pi
!
!------- calculate source contribution to Psi  for  1-0  half-panel
            dxinv = 1.0/(x1-x0)
            psum = x0*(t0-apan) - x1*(t1-apan) + 0.5*yy*(g1-g0)
            pdif = ((x1+x0)*psum+rs1*(t1-apan)-rs0*(t0-apan)+(x0-x1)*yy)&
&             *dxinv
!
            psx1 = -(t1-apan)
            psx0 = t0 - apan
            psyy = 0.5*(g1-g0)
!
            pdx1 = ((x1+x0)*psx1+psum+2.0*x1*(t1-apan)-pdif)*dxinv
            pdx0 = ((x1+x0)*psx0+psum-2.0*x0*(t0-apan)+pdif)*dxinv
            pdyy = ((x1+x0)*psyy+2.0*(x0-x1+yy*(t1-t0)))*dxinv
!
            arg1 = (x(jp)-x(jm))**2 + (y(jp)-y(jm))**2
            dsm = SQRT(arg1)
            dsim = 1.0/dsm
!
!CC      SIG0 = (SIG(JP) - SIG(JO))*DSIO
!CC      SIG1 = (SIG(JP) - SIG(JM))*DSIM
!CC      SSUM = SIG0 + SIG1
!CC      SDIF = SIG0 - SIG1
!
            ssum = (sig(jp)-sig(jo))*dsio + (sig(jp)-sig(jm))*dsim
            sdif = (sig(jp)-sig(jo))*dsio - (sig(jp)-sig(jm))*dsim
!
            psi = psi + qopi*(psum*ssum+pdif*sdif)
!
!------- dPsi/dm
            dzdm(jm) = dzdm(jm) + qopi*(-(psum*dsim)+pdif*dsim)
            dzdm(jo) = dzdm(jo) + qopi*(-(psum*dsio)-pdif*dsio)
            dzdm(jp) = dzdm(jp) + qopi*(psum*(dsio+dsim)+pdif*(dsio-dsim&
&             ))
!
!------- dPsi/dni
            psni = psx1*x1i + psx0*(x1i+x2i)*0.5 + psyy*yyi
            pdni = pdx1*x1i + pdx0*(x1i+x2i)*0.5 + pdyy*yyi
            psi_ni = psi_ni + qopi*(psni*ssum+pdni*sdif)
!
            qtanm = qtanm + qopi*(psni*ssum+pdni*sdif)
!
            dqdm(jm) = dqdm(jm) + qopi*(-(psni*dsim)+pdni*dsim)
            dqdm(jo) = dqdm(jo) + qopi*(-(psni*dsio)-pdni*dsio)
            dqdm(jp) = dqdm(jp) + qopi*(psni*(dsio+dsim)+pdni*(dsio-dsim&
&             ))
!
!
!------- calculate source contribution to Psi  for  0-2  half-panel
            dxinv = 1.0/(x0-x2)
            psum = x2*(t2-apan) - x0*(t0-apan) + 0.5*yy*(g0-g2)
            pdif = ((x0+x2)*psum+rs0*(t0-apan)-rs2*(t2-apan)+(x2-x0)*yy)&
&             *dxinv
!
            psx0 = -(t0-apan)
            psx2 = t2 - apan
            psyy = 0.5*(g0-g2)
!
            pdx0 = ((x0+x2)*psx0+psum+2.0*x0*(t0-apan)-pdif)*dxinv
            pdx2 = ((x0+x2)*psx2+psum-2.0*x2*(t2-apan)+pdif)*dxinv
            pdyy = ((x0+x2)*psyy+2.0*(x2-x0+yy*(t0-t2)))*dxinv
