&             + qopi*gdif*(pdx1*x1p+pdx2*x2p+pdyy*yyp)
!------- dPsi/dP
            z_qdof0 = z_qdof0 + qopi*((psis-psid)*qf0(jo)+(psis+psid)*&
&             qf0(jp))
            z_qdof1 = z_qdof1 + qopi*((psis-psid)*qf1(jo)+(psis+psid)*&
&             qf1(jp))
            z_qdof2 = z_qdof2 + qopi*((psis-psid)*qf2(jo)+(psis+psid)*&
&             qf2(jp))
            z_qdof3 = z_qdof3 + qopi*((psis-psid)*qf3(jo)+(psis+psid)*&
&             qf3(jp))
          END IF
        END IF
