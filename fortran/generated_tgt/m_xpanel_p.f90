!
          dqdg(jo) = dqdg(jo) + qopi*(psni-pdni)
          dqdg(jp) = dqdg(jp) + qopi*(psni+pdni)
!
          IF (geolin) THEN
!
!------- dPsi/dn
            dzdn(jo) = dzdn(jo) + qopi*gsum*(psx1*x1o+psx2*x2o+psyy*yyo)&
&             + qopi*gdif*(pdx1*x1o+pdx2*x2o+pdyy*yyo)
