    retyp = 1
    reinf1 = 0.
    acrit(1) = 9.0
    acrit(2) = 9.0
    xstrip(1) = 1.0
    xstrip(2) = 1.0
    xoctr(1) = 1.0
    xoctr(2) = 1.0
    yoctr(1) = 0.
    yoctr(2) = 0.
    waklen = 1.0
