    CALL BLPINI()
!
!---- Newton iteration limit
    itmax = 20
!
!---- max number of unconverged sequence points for early exit
    nseqex = 4
!
!---- drop tolerance for BL system solver
    vaccel = 0.01
!
!---- inverse-mapping auto-filter level
    ffilt = 0.0
!
!---- default overlay airfoil filename
    oname = ' '
