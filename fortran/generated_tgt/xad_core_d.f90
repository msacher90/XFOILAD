!---- u/Qinf scale factor for profile plotting
    uprwt = 0.02
!
!---- polar variables to be written to polar save file
    ipol(1) = ial
    ipol(2) = icl
    ipol(3) = icd
    ipol(4) = icp
    ipol(5) = icm
    nipol = 5
    nipol0 = 5
!
    jpol(1) = jtn
    jpol(2) = jti
    njpol = 2
