    npol = 0
    ipact = 0
    DO ip=1,npx
      pfname(ip) = ' '
      pfnamx(ip) = ' '
    END DO
!
!---- no reference polars
    npolref = 0
!
!---- plot aspect ratio, character size
    plotar = 0.55
    ch = 0.015
