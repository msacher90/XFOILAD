&   , z_cf1, z_cf2, z_cfa, z_cfm, z_cfx, z_cq1, z_cq2, z_cqa, z_d1, z_d2&
&   , z_da, z_de1, z_de2, z_dea, z_di1, z_di2, z_dix, z_dxi, z_ha, z_hca&
&   , z_hk1, z_hk2, z_hka, z_hl, z_hs1, z_hs2, z_hwa, z_ma, z_s1, z_s2, &
&   z_sa, z_sl, z_t1, z_t2, z_tl, z_u1, z_u2, z_ul, z_upw, z_us1, z_us2&
&   , z_usa, z_x1, z_x2, z_xl
    INTRINSIC LOG
    INTRINSIC ABS
    INTRINSIC MIN
    INTRINSIC EXP
