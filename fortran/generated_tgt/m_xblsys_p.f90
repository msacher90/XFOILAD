    rt2_u2 = rt2*(1.0/u2+r2_u2/r2-v2_u2/v2)
    rt2_t2 = rt2/t2
    rt2_ms = rt2*(r2_ms/r2-v2_ms/v2)
    rt2_re = rt2*(-(v2_re/v2))
