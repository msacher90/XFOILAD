  SUBROUTINE BLKIN()
!----------------------------------------------------------
!     Calculates turbulence-independent secondary "2"
!     variables from the primary "2" variables.
!----------------------------------------------------------
    USE I_XBL
    IMPLICIT NONE
!
!
!*** Start of declarations rewritten by SPAG
!
! Local variables
!
    REAL :: herat, he_ms, he_u2, hk2_h2, hk2_m2, tr2, v2_he
