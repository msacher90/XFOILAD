    result1 = SQRT(arg1)
    v2 = result1*(1.0+hvrat)/(herat+hvrat)/reybl
    v2_he = v2*(1.5/herat-1.0/(herat+hvrat))
!
    v2_u2 = v2_he*he_u2
    v2_ms = -(v2/reybl*reybl_ms) + v2_he*he_ms
