        rdn2 = rlx*dn2
        IF (dn2 .GE. 0.) THEN
          abs2 = dn2
        ELSE
          abs2 = -dn2
        END IF
        IF (rmxbl .GE. 0.) THEN
          abs6 = rmxbl
        ELSE
          abs6 = -rmxbl
        END IF
        IF (abs2 .GT. abs6) THEN
