    REAL :: ami, chsq, chx, chy, clmr, cte, cte_cte1, cte_cte2, cte_tte1&
&   , cte_tte2, cti, d1_a, d2_a, d2_m2, d2_u2, dds1, dds2, dsi, dswaki, &
&   dte, dte_mte1, dte_mte2, dte_ute1, dte_ute2, due1, due2, dule1, &
&   dule2, herat, herat_ms, ma_clmr, mdi, msq_clmr, re_clmr, str, temp, &
&   thi, tte, tte_tte1, tte_tte2, u1_a, u2_a, uei, ule1_a, ule2_a, &
&   xi_ule1, xi_ule2, xsi, xtr, ytr
    REAL, DIMENSION(2*ivx) :: d1_m, d2_m, u1_m, u2_m, ule1_m, ule2_m, &
&   ute1_m, ute2_m
    INTEGER :: i, ibl, icom, ile1, ile2, is, ite1, ite2, iv, iw, j, jbl&
&   , js, jv, jvte1, jvte2
    REAL, DIMENSION(ivx, 2) :: usav
    REAL :: xr1, xr2
    INTRINSIC SQRT
    INTRINSIC FLOAT
    REAL :: pwx1
    REAL :: pwy1
    REAL :: arg1
    REAL :: result1
!
!*** End of declarations rewritten by SPAG
!
!
!*** Start of declarations rewritten by SPAG
!
! Local variables
!
!
!*** End of declarations rewritten by SPAG
    setbl = .true.
!
!-------------------------------------------------
!     Sets up the BL Newton system coefficients
!     for the current BL variables and the edge
!     velocities received from SETUP. The local
!     BL system coefficients are then
!     incorporated into the global Newton system.
!-------------------------------------------------
!
!---- set the CL used to define Mach, Reynolds numbers
    IF (lalfa) THEN
      clmr = cl
    ELSE
      clmr = clspec
    END IF
!
!---- set current MINF(CL)
    CALL MRCL(clmr, ma_clmr, re_clmr)
    msq_clmr = 2.0*minf*ma_clmr
!
!---- set compressibility parameter TKLAM and derivative TK_MSQ
    CALL COMSET()
!
!---- set gas constant (= Cp/Cv)
    gambl = gamma
    gm1bl = gamm1
!
!---- set parameters for compressibility correction
    qinfbl = qinf
    tkbl = tklam
    tkbl_ms = tkl_msq
!
!---- stagnation density and 1/enthalpy
    pwx1 = 1.0 + 0.5*gm1bl*minf**2
    pwy1 = 1.0/gm1bl
    rstbl = pwx1**pwy1
    rstbl_ms = 0.5*rstbl/(1.0+0.5*gm1bl*minf**2)
!
    hstinv = gm1bl*(minf/qinfbl)**2/(1.0+0.5*gm1bl*minf**2)
    hstinv_ms = gm1bl*(1.0/qinfbl)**2/(1.0+0.5*gm1bl*minf**2) - 0.5*&
&     gm1bl*hstinv/(1.0+0.5*gm1bl*minf**2)
!
!---- set Reynolds number based on freestream density, velocity, viscosity
    herat = 1.0 - 0.5*qinfbl**2*hstinv
    herat_ms = -(0.5*qinfbl**2*hstinv_ms)
!
    arg1 = herat**3
    result1 = SQRT(arg1)
    reybl = reinf*result1*(1.0+hvrat)/(herat+hvrat)
    arg1 = herat**3
    result1 = SQRT(arg1)
    reybl_re = result1*(1.0+hvrat)/(herat+hvrat)
    reybl_ms = reybl*(1.5/herat-1.0/(herat+hvrat))*herat_ms
!
    idampv = idamp
!
!---- save TE thickness
    dwte = wgap(1)
!
    IF (.NOT.lblini) THEN
!----- initialize BL by marching with Ue (fudge at separation)
      IF (show_output) THEN
        WRITE(*, *) 
        WRITE(*, *) 'Initializing BL ...'
      END IF
      setbl = MRCHUE()
      IF (setbl) THEN
        lblini = .true.
      ELSE IF (abort_on_nan) THEN
        RETURN
      END IF
    END IF
!
    IF (show_output) WRITE(*, *) 
!
!---- march BL with current Ue and Ds to establish transition
    setbl = MRCHDU()
    IF (abort_on_nan .AND. (.NOT.setbl)) THEN
      RETURN
    ELSE
!
      DO is=1,2
        DO ibl=2,nbl(is)
          usav(ibl, is) = uedg(ibl, is)
        END DO
      END DO
!
      CALL UESET()
!
      DO is=1,2
        DO ibl=2,nbl(is)
          temp = usav(ibl, is)
          usav(ibl, is) = uedg(ibl, is)
          uedg(ibl, is) = temp
        END DO
      END DO
!
      ile1 = ipan(2, 1)
      ile2 = ipan(2, 2)
      ite1 = ipan(iblte(1), 1)
      ite2 = ipan(iblte(2), 2)
!
      jvte1 = isys(iblte(1), 1)
      jvte2 = isys(iblte(2), 2)
!
      dule1 = uedg(2, 1) - usav(2, 1)
      dule2 = uedg(2, 2) - usav(2, 2)
!
!---- set LE and TE Ue sensitivities wrt all m values
      DO js=1,2
        DO jbl=2,nbl(js)
          j = ipan(jbl, js)
          jv = isys(jbl, js)
          ule1_m(jv) = -(vti(2, 1)*vti(jbl, js)*dij(ile1, j))
          ule2_m(jv) = -(vti(2, 2)*vti(jbl, js)*dij(ile2, j))
          ute1_m(jv) = -(vti(iblte(1), 1)*vti(jbl, js)*dij(ite1, j))
          ute2_m(jv) = -(vti(iblte(2), 2)*vti(jbl, js)*dij(ite2, j))
        END DO
      END DO
!
      ule1_a = uinv_a(2, 1)
      ule2_a = uinv_a(2, 2)
!
      tindex(1) = 0.0
      tindex(2) = 0.0
!
!**** Go over each boundary layer/wake
      DO is=1,2
!
!---- there is no station "1" at similarity, so zero everything out
        DO js=1,2
          DO jbl=2,nbl(js)
            jv = isys(jbl, js)
            u1_m(jv) = 0.
            d1_m(jv) = 0.
          END DO
        END DO
        u1_a = 0.
        d1_a = 0.
!
        due1 = 0.
        dds1 = 0.
!
!---- similarity station pressure gradient parameter  x/u du/dx
        ibl = 2
        bule = 1.0
!
        amcrit = acrit(is)
!
!---- set forced transition arc length position
        CALL XIFSET(is)
!
        tran = .false.
        turb = .false.
!
!**** Sweep downstream setting up BL equation linearizations
        DO ibl=2,nbl(is)
!
          iv = isys(ibl, is)
!
          simi = ibl .EQ. 2
          wake = ibl .GT. iblte(is)
          tran = ibl .EQ. itran(is)
          turb = ibl .GT. itran(is)
!
          i = ipan(ibl, is)
!
!---- set primary variables for current station
          xsi = xssi(ibl, is)
          IF (ibl .LT. itran(is)) ami = ctau(ibl, is)
          IF (ibl .GE. itran(is)) cti = ctau(ibl, is)
          uei = uedg(ibl, is)
          thi = thet(ibl, is)
          mdi = mass(ibl, is)
!
          dsi = mdi/uei
!
          IF (wake) THEN
            iw = ibl - iblte(is)
            dswaki = wgap(iw)
          ELSE
            dswaki = 0.
          END IF
!
!---- set derivatives of DSI (= D2)
          d2_m2 = 1.0/uei
          d2_u2 = -(dsi/uei)
!
          DO js=1,2
            DO jbl=2,nbl(js)
              j = ipan(jbl, js)
              jv = isys(jbl, js)
              u2_m(jv) = -(vti(ibl, is)*vti(jbl, js)*dij(i, j))
              d2_m(jv) = d2_u2*u2_m(jv)
            END DO
          END DO
          d2_m(iv) = d2_m(iv) + d2_m2
!
          u2_a = uinv_a(ibl, is)
          d2_a = d2_u2*u2_a
!
!---- "forced" changes due to mismatch between UEDG and USAV=UINV+dij*MASS
          due2 = uedg(ibl, is) - usav(ibl, is)
          dds2 = d2_u2*due2
!
          CALL BLPRV(xsi, ami, cti, thi, dsi, dswaki, uei)
          CALL BLKIN()
!
!---- check for transition and set TRAN, XT, etc. if found
          IF (tran) THEN
            setbl = TRCHEK()
            IF (abort_on_nan .AND. (.NOT.setbl)) THEN
              RETURN
            ELSE
              ami = ampl2
            END IF
          END IF
          IF (ibl .EQ. itran(is) .AND. (.NOT.tran) .AND. show_output) &
&           WRITE(*, *) 'SETBL: Xtr???  n1 n2: ', ampl1, ampl2
!
!---- assemble 10x4 linearized system for dCtau, dTh, dDs, dUe, dXi
!     at the previous "1" station and the current "2" station
!
          IF (ibl .EQ. iblte(is) + 1) THEN
!
!----- define quantities at start of wake, adding TE base thickness to Dstar
            tte = thet(iblte(1), 1) + thet(iblte(2), 2)
            dte = dstr(iblte(1), 1) + dstr(iblte(2), 2) + ante
            cte = (ctau(iblte(1), 1)*thet(iblte(1), 1)+ctau(iblte(2), 2)&
&             *thet(iblte(2), 2))/tte
            CALL TESYS(cte, tte, dte)
!
            tte_tte1 = 1.0
            tte_tte2 = 1.0
            dte_mte1 = 1.0/uedg(iblte(1), 1)
            dte_ute1 = -(dstr(iblte(1), 1)/uedg(iblte(1), 1))
            dte_mte2 = 1.0/uedg(iblte(2), 2)
            dte_ute2 = -(dstr(iblte(2), 2)/uedg(iblte(2), 2))
            cte_cte1 = thet(iblte(1), 1)/tte
            cte_cte2 = thet(iblte(2), 2)/tte
            cte_tte1 = (ctau(iblte(1), 1)-cte)/tte
            cte_tte2 = (ctau(iblte(2), 2)-cte)/tte
!
!----- re-define D1 sensitivities wrt m since D1 depends on both TE Ds values
            DO js=1,2
              DO jbl=2,nbl(js)
                j = ipan(jbl, js)
                jv = isys(jbl, js)
                d1_m(jv) = dte_ute1*ute1_m(jv) + dte_ute2*ute2_m(jv)
              END DO
            END DO
            d1_m(jvte1) = d1_m(jvte1) + dte_mte1
            d1_m(jvte2) = d1_m(jvte2) + dte_mte2
!
!----- "forced" changes from  UEDG --- USAV=UINV+dij*MASS  mismatch
            due1 = 0.
            dds1 = dte_ute1*(uedg(iblte(1), 1)-usav(iblte(1), 1)) + &
&             dte_ute2*(uedg(iblte(2), 2)-usav(iblte(2), 2))
!
          ELSE
!
            CALL BLSYS()
!
          END IF
!
!
!---- Save wall shear and equil. max shear coefficient for plotting output
          tau(ibl, is) = 0.5*r2*u2*u2*cf2
          dis(ibl, is) = r2*u2*u2*u2*di2*hs2*0.5
          ctq(ibl, is) = cq2
          delt(ibl, is) = de2
          uslp(ibl, is) = 1.60/(1.0+us2)
!
!@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@
!      IF(WAKE) THEN
!        ALD = DLCON
!      ELSE
!       ALD = 1.0
!      ENDIF
!C
!      IF(TURB .AND. .NOT.WAKE) THEN
!        GCC = GCCON
!        HKC     = HK2 - 1.0 - GCC/RT2
!        IF(HKC .LT. 0.01) THEN
!         HKC = 0.01
!        ENDIF
!       ELSE
!        HKC = HK2 - 1.0
!       ENDIF
!C
!       HR = HKC     / (GACON*ALD*HK2)
!       UQ = (0.5*CF2 - HR**2) / (GBCON*D2)
!C
!       IF(TURB) THEN
!        IBLP = MIN(IBL+1,NBL(IS))
!        IBLM = MAX(IBL-1,2      )
!        DXSSI = XSSI(IBLP,IS) - XSSI(IBLM,IS)
!        IF(DXXSI.EQ.0.0) DXSSI = 1.0
!        GUXD(IBL,IS) = -LOG(UEDG(IBLP,IS)/UEDG(IBLM,IS)) / DXSSI
!        GUXQ(IBL,IS) = -UQ
!       ELSE
!        GUXD(IBL,IS) = 0.0
!        GUXQ(IBL,IS) = 0.0
!       ENDIF
!@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@
!
!---- set XI sensitivities wrt LE Ue changes
          IF (is .EQ. 1) THEN
            xi_ule1 = sst_go
            xi_ule2 = -sst_gp
          ELSE
            xi_ule1 = -sst_go
            xi_ule2 = sst_gp
          END IF
!
!---- stuff BL system coefficients into main Jacobian matrix
!
          DO jv=1,nsys
            vm(1, jv, iv) = vs1(1, 3)*d1_m(jv) + vs1(1, 4)*u1_m(jv) + &
&             vs2(1, 3)*d2_m(jv) + vs2(1, 4)*u2_m(jv) + (vs1(1, 5)+vs2(1&
&             , 5)+vsx(1))*(xi_ule1*ule1_m(jv)+xi_ule2*ule2_m(jv))
          END DO
!
          vb(1, 1, iv) = vs1(1, 1)
          vb(1, 2, iv) = vs1(1, 2)
!
          va(1, 1, iv) = vs2(1, 1)
          va(1, 2, iv) = vs2(1, 2)
!
          IF (lalfa) THEN
            vdel(1, 2, iv) = vsr(1)*re_clmr + vsm(1)*msq_clmr
          ELSE
            vdel(1, 2, iv) = vs1(1, 4)*u1_a + vs1(1, 3)*d1_a + (vs2(1, 4&
&             )*u2_a+vs2(1, 3)*d2_a) + (vs1(1, 5)+vs2(1, 5)+vsx(1))*(&
&             xi_ule1*ule1_a+xi_ule2*ule2_a)
          END IF
!
          vdel(1, 1, iv) = vsrez(1) + (vs1(1, 4)*due1+vs1(1, 3)*dds1) + &
&           (vs2(1, 4)*due2+vs2(1, 3)*dds2) + (vs1(1, 5)+vs2(1, 5)+vsx(1&
&           ))*(xi_ule1*dule1+xi_ule2*dule2)
!
!
          DO jv=1,nsys
            vm(2, jv, iv) = vs1(2, 3)*d1_m(jv) + vs1(2, 4)*u1_m(jv) + &
&             vs2(2, 3)*d2_m(jv) + vs2(2, 4)*u2_m(jv) + (vs1(2, 5)+vs2(2&
&             , 5)+vsx(2))*(xi_ule1*ule1_m(jv)+xi_ule2*ule2_m(jv))
          END DO
!
          vb(2, 1, iv) = vs1(2, 1)
          vb(2, 2, iv) = vs1(2, 2)
!
          va(2, 1, iv) = vs2(2, 1)
          va(2, 2, iv) = vs2(2, 2)
!
          IF (lalfa) THEN
            vdel(2, 2, iv) = vsr(2)*re_clmr + vsm(2)*msq_clmr
          ELSE
            vdel(2, 2, iv) = vs1(2, 4)*u1_a + vs1(2, 3)*d1_a + (vs2(2, 4&
&             )*u2_a+vs2(2, 3)*d2_a) + (vs1(2, 5)+vs2(2, 5)+vsx(2))*(&
&             xi_ule1*ule1_a+xi_ule2*ule2_a)
          END IF
!
          vdel(2, 1, iv) = vsrez(2) + (vs1(2, 4)*due1+vs1(2, 3)*dds1) + &
&           (vs2(2, 4)*due2+vs2(2, 3)*dds2) + (vs1(2, 5)+vs2(2, 5)+vsx(2&
&           ))*(xi_ule1*dule1+xi_ule2*dule2)
!
!
          DO jv=1,nsys
            vm(3, jv, iv) = vs1(3, 3)*d1_m(jv) + vs1(3, 4)*u1_m(jv) + &
&             vs2(3, 3)*d2_m(jv) + vs2(3, 4)*u2_m(jv) + (vs1(3, 5)+vs2(3&
&             , 5)+vsx(3))*(xi_ule1*ule1_m(jv)+xi_ule2*ule2_m(jv))
          END DO
!
          vb(3, 1, iv) = vs1(3, 1)
          vb(3, 2, iv) = vs1(3, 2)
!
          va(3, 1, iv) = vs2(3, 1)
          va(3, 2, iv) = vs2(3, 2)
!
          IF (lalfa) THEN
            vdel(3, 2, iv) = vsr(3)*re_clmr + vsm(3)*msq_clmr
          ELSE
            vdel(3, 2, iv) = vs1(3, 4)*u1_a + vs1(3, 3)*d1_a + (vs2(3, 4&
&             )*u2_a+vs2(3, 3)*d2_a) + (vs1(3, 5)+vs2(3, 5)+vsx(3))*(&
&             xi_ule1*ule1_a+xi_ule2*ule2_a)
          END IF
!
          vdel(3, 1, iv) = vsrez(3) + (vs1(3, 4)*due1+vs1(3, 3)*dds1) + &
&           (vs2(3, 4)*due2+vs2(3, 3)*dds2) + (vs1(3, 5)+vs2(3, 5)+vsx(3&
&           ))*(xi_ule1*dule1+xi_ule2*dule2)
!
!
          IF (ibl .EQ. iblte(is) + 1) THEN
!
!----- redefine coefficients for TTE, DTE, etc
            vz(1, 1) = vs1(1, 1)*cte_cte1
            vz(1, 2) = vs1(1, 1)*cte_tte1 + vs1(1, 2)*tte_tte1
            vb(1, 1, iv) = vs1(1, 1)*cte_cte2
            vb(1, 2, iv) = vs1(1, 1)*cte_tte2 + vs1(1, 2)*tte_tte2
!
            vz(2, 1) = vs1(2, 1)*cte_cte1
            vz(2, 2) = vs1(2, 1)*cte_tte1 + vs1(2, 2)*tte_tte1
            vb(2, 1, iv) = vs1(2, 1)*cte_cte2
            vb(2, 2, iv) = vs1(2, 1)*cte_tte2 + vs1(2, 2)*tte_tte2
!
            vz(3, 1) = vs1(3, 1)*cte_cte1
            vz(3, 2) = vs1(3, 1)*cte_tte1 + vs1(3, 2)*tte_tte1
            vb(3, 1, iv) = vs1(3, 1)*cte_cte2
            vb(3, 2, iv) = vs1(3, 1)*cte_tte2 + vs1(3, 2)*tte_tte2
!
          END IF
!
!---- turbulent intervals will follow if currently at transition interval
          IF (tran) THEN
            turb = .true.
!
!------ save transition location
            itran(is) = ibl
            tforce(is) = trforc
            xssitr(is) = xt
!
!------ interpolate airfoil geometry to find transition x/c
!-      (for user output)
            IF (is .EQ. 1) THEN
              str = sst - xt
            ELSE
              str = sst + xt
            END IF
            chx = xte - xle
            chy = yte - yle
            chsq = chx**2 + chy**2
            xtr = SEVAL(str, x, xp, s, n)
            ytr = SEVAL(str, y, yp, s, n)
            xoctr(is) = ((xtr-xle)*chx+(ytr-yle)*chy)/chsq
            yoctr(is) = ((ytr-yle)*chx-(xtr-xle)*chy)/chsq
          END IF
!
          tran = .false.
!
          IF (ibl .EQ. iblte(is)) THEN
!----- set "2" variables at TE to wake correlations for next station
!
            turb = .true.
            wake = .true.
            CALL BLVAR(3)
            CALL BLMID(3)
          END IF
!
          DO js=1,2
            DO jbl=2,nbl(js)
              jv = isys(jbl, js)
              u1_m(jv) = u2_m(jv)
              d1_m(jv) = d2_m(jv)
            END DO
          END DO
!
          u1_a = u2_a
          d1_a = d2_a
!
          due1 = due2
          dds1 = dds2
!
          xr1 = x1
          xr2 = x2
! if (ibl==ITRan(is) .and. X2>X1) then
          IF (ibl .EQ. itran(is) .AND. xr2 .GT. xr1) THEN
            IF (is .EQ. 1) THEN
              tindex(is) = FLOAT(ist - itran(is) + 3) - (xt-x1)/(x2-x1)
            ELSE
              tindex(is) = FLOAT(ist + itran(is) - 2) + (xt-x1)/(x2-x1)
            END IF
          END IF
!
!---- set BL variables for next station
          CALL BLC_1FROM2()
        END DO
!
!---- next streamwise station
!
        IF (tforce(is)) THEN
          IF (show_output) WRITE(*, 99001) is, xoctr(is), itran(is)
        ELSE IF (show_output) THEN
          WRITE(*, 99002) is, xoctr(is), itran(is)
        END IF
      END DO
    END IF
99001 FORMAT(1x, 'Side', i2, ' forced transition at x/c = ', f7.4, i5)
99002 FORMAT(1x, 'Side', i2, '  free  transition at x/c = ', f7.4, i5)
  END FUNCTION SETBL

!  Differentiation of mrchue in forward (tangent) mode (with options r8 messagesInFile):
!   variations   of useful results: di2_t2 rt1_ms hk1_ms hs2_re
!                di1 di2_d2 di2 u1_ms xt_re cq2_re v1 di1_t1 us2_u2
!                v1_u1 hc2_u2 hk1 di1_d1 hs1_re vs1 vs2 hs2_t2
!                s1 cq1_re xt_t1 de2_t2 us1_u1 xt_t2 cf2_u2 cq2_t2
!                hc1_u1 hs2_d2 u1_uei m1_u1 xt_d1 de2_d2 xt_d2
!                cq2_d2 hs1_t1 de1_t1 r1_u1 cf1_u1 cq1_t1 us2_ms
!                hc2_ms hs1_d1 v1_ms xt_a1 de1_d1 m1 cq1_d1 di2_u2
!                cf2_ms us1_ms hc1_ms xt m1_ms dw1 di1_u1 xt_x1
!                xt_x2 r1_ms cf1_ms rt1_re hs2_u2 t1 xt_u1 de2_u2
!                xt_u2 cq2_u2 di2_ms d1 cf1 vsrez cf2 us1 us2 hs1_u1
!                rt1_t1 hk1_t1 de1_u1 cq1_u1 di1_ms hk1_d1 hs1
!                hs2 hc1 hs2_ms hc2 de2_ms xt_ms cq2_ms us2_re
!                v1_re di2_s2 c2sav x1 hs1_ms vsm de1_ms h1 cq1_ms
!                cf2_re us1_re u1 di1_s1 us2_t2 vsr hc2_t2 c1sav
!                de1 de2 us2_d2 hc2_d2 h1_t1 r1 vsx cf1_re rt1_u1
!                ampl1 hk1_u1 us1_t1 cf2_t2 hc1_t1 h1_d1 di2_re
!                us1_d1 cf2_d2 hc1_d1 cq1 cq2 cf1_t1 cf1_d1 di1_re
