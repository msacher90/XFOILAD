        rlxd = -(dclmax*dacd/dac**2)
        rlx = dclmax/dac
      ELSE
        rlxd = 0.0_8
      END IF
      IF (rlx*dac .LT. dclmin) THEN
        rlxd = (dclmind-dclmin*dacd/dac)/dac
        rlx = dclmin/dac
      END IF
    ELSE
