        IF (abs0 .GT. abs1) THEN
          apx1 = ATAN2(s1, c1)
          apx2 = apx1 + 0.5*pi
        ELSE
          apx2 = ATAN2(s2, c2)
          apx1 = apx2 - 0.5*pi
        END IF
        IF (apx1 .LT. -(0.5*pi)) apx1 = apx1 + pi
        IF (apx1 .GT. 0.5*pi) apx1 = apx1 - pi
        IF (apx2 .LT. -(0.5*pi)) apx2 = apx2 + pi
        IF (apx2 .GT. 0.5*pi) apx2 = apx2 - pi
      END IF
    END IF
  END SUBROUTINE AECALC

