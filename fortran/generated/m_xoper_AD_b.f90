  SUBROUTINE SPECCL_BWD()
    USE M_XPANEL_DIFF, ONLY : qiset, qiset_fwd, qiset_bwd, ggcalc, ggcalc_fwd, ggcalc_bwd
    USE I_XFOIL_DIFF
    USE S_XFOIL_DIFF, ONLY : mrcl, mrcl_fwd, mrcl_bwd, comset, comset_fwd, comset_bwd, clcalc, clcalc_fwd, &
