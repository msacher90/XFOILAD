      arg1 = n + nw
      qvisb = 0.0_8
      CALL CPCALC_BWD(arg1, qvis, qvisb, qinf, minf, minfb, cpv, cpvb)
    ELSE
      CALL CPCALC_BWD(n, qinv, qinvb, qinf, minf, minfb, cpi, cpib)
    END IF
    CALL QISET_BWD()
    CALL TECALC_BWD()
    CALL POPCONTROL1B(branch)
    CALL POPINTEGER4(ad_count)
    DO 100 i0=1,ad_count
      IF (i0 .EQ. 1) THEN
        CALL POPCONTROL1B(branch)
        IF (branch .EQ. 0) THEN
          cl_alfb = 0.0_8
          gam_ab = 0.0_8
          GOTO 100
        ELSE
          cl_alfb = 0.0_8
          gam_ab = 0.0_8
        END IF
      END IF
