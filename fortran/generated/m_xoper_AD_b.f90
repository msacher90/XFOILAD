  SUBROUTINE SPECCL()
    USE M_XPANEL_DIFF, ONLY : qiset, ggcalc
    USE I_XFOIL_DIFF
    USE S_XFOIL_DIFF, ONLY : mrcl, comset, clcalc, cpcalc, tecalc
    IMPLICIT NONE
