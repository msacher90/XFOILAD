&               , alfab, minf, minfb, qinf, xcmref, ycmref, cl, clb, cm&
&               , cmb, cdp, cl_alf, cl_alfb, cl_msq, cl_msqb)
      cosab = 0.0_8
      sinab = 0.0_8
      DO i=n,1,-1
        CALL POPREAL8(gam_a(i))
        cosab = cosab + gamu(i, 2)*gam_ab(i) + gamu(i, 1)*gamb(i)
