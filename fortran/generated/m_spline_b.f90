  SUBROUTINE SPLNXY(x, xs, y, ys, s, n)
    USE I_XFOIL_DIFF, ONLY : show_output
    IMPLICIT NONE
!
!
!
!*** Start of declarations rewritten by SPAG
!
! PARAMETER definitions
!
    INTEGER, PARAMETER :: kmax=32
!
! Dummy arguments
!
    INTEGER :: n
    REAL, DIMENSION(n) :: s, x, xs, y, ys
! intent (inout) S
!
! Local variables
!
    REAL :: cx1, cx2, cy1, cy2, ds, dx, dy, serr, sint, sint1, sint2, t
    INTEGER :: i, ipass, k, kk, npass
    REAL, DIMENSION(0:kmax) :: xt, yt
    INTRINSIC FLOAT
    INTRINSIC SQRT
    INTRINSIC ABS
    REAL :: abs0
    REAL :: abs1
    REAL :: abs2
!
!*** End of declarations rewritten by SPAG
!
!
!*** Start of declarations rewritten by SPAG
!
! PARAMETER definitions
!
!
! Dummy arguments
!
!
! Local variables
!
!
!*** End of declarations rewritten by SPAG
!
!-----------------------------------------
!     Splines 2-D shape X(S), Y(S), along |
!     with true arc length parameter S.   |
!-----------------------------------------
!
    kk = kmax
    npass = 10
!
!---- set first estimate of arc length parameter
    CALL SCALC(x, y, s, n)
!
!---- spline X(S) and Y(S)
    CALL SEGSPL(x, xs, s, n)
    CALL SEGSPL(y, ys, s, n)
!
!---- re-integrate true arc length
    DO ipass=1,npass
!
      serr = 0.
!
      ds = s(2) - s(1)
      DO i=2,n
        dx = x(i) - x(i-1)
        dy = y(i) - y(i-1)
!
        cx1 = ds*xs(i-1) - dx
        cx2 = ds*xs(i) - dx
        cy1 = ds*ys(i-1) - dy
        cy2 = ds*ys(i) - dy
!
        xt(0) = 0.
        yt(0) = 0.
        DO k=1,kk-1
          t = FLOAT(k)/FLOAT(kk)
          xt(k) = t*dx + (t-t*t)*((1.0-t)*cx1-t*cx2)
          yt(k) = t*dy + (t-t*t)*((1.0-t)*cy1-t*cy2)
        END DO
        xt(kk) = dx
        yt(kk) = dy
!
        sint1 = 0.
        DO k=1,kk
          sint1 = sint1 + SQRT((xt(k)-xt(k-1))**2 + (yt(k)-yt(k-1))**2)
        END DO
!
        sint2 = 0.
        DO k=2,kk,2
          sint2 = sint2 + SQRT((xt(k)-xt(k-2))**2 + (yt(k)-yt(k-2))**2)
        END DO
!
        sint = (4.0*sint1-sint2)/3.0
        IF (sint - ds .GE. 0.) THEN
          abs0 = sint - ds
        ELSE
          abs0 = -(sint-ds)
        END IF
        IF (serr .GE. 0.) THEN
          abs2 = serr
        ELSE
          abs2 = -serr
        END IF
!
        IF (abs0 .GT. abs2) serr = sint - ds
!
        IF (i .LT. n) ds = s(i+1) - s(i)
!
        s(i) = s(i-1) + SQRT(sint)
      END DO
!
      serr = serr/(s(n)-s(1))
      IF (show_output) WRITE(*, *) ipass, serr
!
!------ re-spline X(S) and Y(S)
      CALL SEGSPL(x, xs, s, n)
      CALL SEGSPL(y, ys, s, n)
      IF (serr .GE. 0.) THEN
        abs1 = serr
      ELSE
        abs1 = -serr
      END IF
!
      IF (abs1 .LT. 1.0e-7) RETURN
    END DO
  END SUBROUTINE SPLNXY

